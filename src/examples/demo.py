# ============================================
# 测试运行
# ============================================

def demo():
    """演示绘图数据系统"""
    print("初始化绘图引擎...")
    engine = DrawingEngine(1000, 700)
    parser = DrawingDataParser(engine)

    # 绘制区域
    bounds = (0, 0, 1000, 700)

    print("绘制粽子...")
    parser.parse(ZONGZI_DATA, bounds)
    engine.update()

    import time
    time.sleep(2)

    print("清空画布...")
    engine.clear()

    print("绘制月饼...")
    parser.parse(MOONCAKE_DATA, bounds)
    engine.update()

    time.sleep(2)

    print("清空画布...")
    engine.clear()

    print("绘制茶壶...")
    parser.parse(TEAPOT_DATA, bounds)
    engine.update()

    print("完成！关闭窗口退出...")
    engine.screen.exitonclick()


if __name__ == '__main__':
    demo()
