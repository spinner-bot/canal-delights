def get_city(index: int) -> dict:
    """获取城市数据。"""
    return CITIES[index % len(CITIES)]


def get_food(city_index: int, food_index: int) -> dict:
    """获取美食数据。"""
    city = get_city(city_index)
    return city['foods'][food_index % len(city['foods'])]


def get_all_cities() -> list:
    """获取所有城市。"""
    return CITIES
